package main.java.inhatc.cse.java.basic.exam3.ex27__1;

public class UserInfo {
    private int age;
    private String name;

    public UserInfo(String name, int age) {
        this.name = name;
        this.age = age;
    }

    public int getAge() {
        return age;
    }

    public String getName() {
        return name;
    }
}
